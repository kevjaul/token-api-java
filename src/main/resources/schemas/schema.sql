DROP TABLE IF EXISTS applications CASCADE;
DROP TABLE IF EXISTS tokens CASCADE;
DROP TABLE IF EXISTS api_keys_scopes CASCADE;
DROP TABLE IF EXISTS api_keys CASCADE;

DROP TYPE IF EXISTS ROLES CASCADE;

CREATE TYPE roles AS ENUM ('ADMIN', 'CLASSIC');

CREATE TABLE applications
(
    ID       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APP_NAME  VARCHAR(256) NOT NULL,
    MAX_TOKEN_AMOUNT  BIGINT NOT NULL,
    MIN_TOKEN_AMOUNT  BIGINT NOT NULL,
    REGENDAYS  INTEGER NOT NULL,
    REGENHOURS  INTEGER NOT NULL,
    REGENMINS INTEGER NOT NULL,
    CHECK (MIN_TOKEN_AMOUNT <= MAX_TOKEN_AMOUNT)
);

CREATE TABLE tokens
(
    USER_ID  VARCHAR(256) NOT NULL,
    TOKEN_AMOUNT  BIGINT NOT NULL,
    LINKED_APP  BIGINT NOT NULL,
    PRIMARY KEY (USER_ID, LINKED_APP),
    CONSTRAINT fk_user_tokens_app
        FOREIGN KEY (LINKED_APP) 
        REFERENCES applications(ID)
);

CREATE TABLE api_keys
(
    HASHED_API_KEY VARCHAR(256) NOT NULL PRIMARY KEY,
    ROLE_TYPE roles NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    EXPIRES_AT TIMESTAMP,
    KEY_STATUS VARCHAR(256) NOT NULL
);

CREATE TABLE api_keys_scopes
(
    HASHED_API_KEY VARCHAR(256) NOT NULL,
    APP_ID BIGINT,
    PRIMARY KEY (HASHED_API_KEY, APP_ID),
    CONSTRAINT fk_api_keys_scopes_api_keys
        FOREIGN KEY (HASHED_API_KEY) 
        REFERENCES api_keys(HASHED_API_KEY),
    CONSTRAINT fk_api_keys_scopes_applications
        FOREIGN KEY (APP_ID) 
        REFERENCES applications(ID)
);

CREATE INDEX idx_tokens_user_id ON tokens(USER_ID);
CREATE INDEX idx_applications_id ON applications(ID);
CREATE INDEX idx_tokens_linked_app ON tokens(LINKED_APP);